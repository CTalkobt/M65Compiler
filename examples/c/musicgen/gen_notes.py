#!/usr/bin/env python3
# Generates notes.h: SID frequency register values for MIDI notes 24-95
# (C1-B6): f = 440 * 2^((n - 69) / 12), reg = f * 2^24 / 985248 (PAL clock)
CLOCK = 985248
lines = ["/* notes.h — generated by gen_notes.py: SID frequency values for MIDI notes */",
         "#define NOTE_LO 24",
         "#define NOTE_HI 95",
         "static const unsigned int note_freq[NOTE_HI - NOTE_LO + 1] = {"]
vals = []
for n in range(24, 96):
    f = 440.0 * 2 ** ((n - 69) / 12)
    vals.append(min(65535, round(f * (1 << 24) / CLOCK)))
for i in range(0, len(vals), 12):
    lines.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
lines.append("};")
open("notes.h", "w").write("\n".join(lines) + "\n")
