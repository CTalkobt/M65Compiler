/* Game flow                                                                */

static void hide_objects(void) {
    unsigned char i;
    for (i = 0; i < 3 + NBOMBS; i++) entities[i]->active = 0;
    cannon.active = 1;
    cannon.dying = 0;
    cannon.pos.x = SX(38);
    cannon.pos.y = SY(CANNON_ROW) - 12;     /* the art is in the sprite's rows 12-19 */
    sprite_image(SPR_CANNON, SPRD_CANNON);
    snd_ufo(0, 0);
}

static void clear_play_area(void) {
    unsigned char r;
    for (r = 1; r < CANNON_ROW; r++) clear_row(r);
}

static void new_wave(void) {
    clear_play_area();
    reset_formation();
    reset_shields();
    hide_objects();
    draw_formation();
    draw_hud();
}

static void start(unsigned char new_state) {
    unsigned char r;
    state = new_state;
    score = 0;
    lives = 3;
    wave = 1;
    for (r = 0; r < ROWS; r++) { clear_row(r); color_row(r, C_WHITE); }
    dma_fill_far(SCREEN_LIN + GROUND_ROW * COLS, COLS, CH_GROUND);
    color_row(GROUND_ROW, C_GREEN);
    new_wave();
    if (state == ATTRACT) message(ATTRACT_TEXT);
}

static void lose_life(void) {
    snd_boom();
    cannon.dying = 60;
    if (state == PLAYING) {
        lives--;
        put_number(HUD_ROW, 66, lives, 1);
        if (lives == 0) {
            state = GAME_OVER;
            state_timer = 150;
            message(s"game over");
        }
    }
}

/* one frame of play */
static void play_frame(void) {
    unsigned char i;

    input_bits = state == ATTRACT ? ai_input() : (state == PLAYING ? read_input() : 0);

    /* fire */
    if ((input_bits & JOY_FIRE) && !shot.active && !cannon.dying && state != GAME_OVER) {
        shot.active = 1;
        shot.pos.x = cannon.pos.x + 7;
        shot.pos.y = cannon.pos.y + 6;
        snd_shot();
    }

    /* drop bombs from the bottom alien of a random column */
    if ((rnd() & 63) < (wave < 6 ? wave : 6))
        for (i = 0; i < NBOMBS; i++)
            if (!bombs[i].active) {
                unsigned char c = (unsigned char)(rnd() % FORM_COLS);
                signed char r;
                for (r = FORM_ROWS - 1; r >= 0 && !alive[r][c]; r--) ;
                if (r >= 0) {
                    bombs[i].active = 1;
                    bombs[i].pos.x = SX(form_x + c * ALIEN_STEP + 1) + 2;
                    bombs[i].pos.y = SY(form_y + r * 2 + 1);
                }
                break;
            }

    /* the UFO now and then */
    if (!ufo.active && (rnd() & 1023) == 0) {
        ufo.active = 1;
        if (rnd() & 1) { ufo.pos.x = SX(0); ufo.vel.x = 1; }
        else { ufo.pos.x = SX(COLS - 4); ufo.vel.x = -1; }
        ufo.pos.y = SY(UFO_ROW);
    }

    /* every object: update and draw, through the Entity interface */
    for (i = 0; i < 3 + NBOMBS; i++) {
        entities[i]->update();
        entities[i]->draw();
    }

    /* shot vs UFO */
    if (shot.active && ufo.active && shot.pos.y <= ufo.pos.y + 6 &&
        shot.pos.x >= ufo.pos.x && shot.pos.x <= ufo.pos.x + 15) {
        shot.active = 0;
        ufo.active = 0;
        snd_ufo(0, 0);
        snd_boom();
        add_score((unsigned int)(50 * (1 + rnd() % 6)));
    }

    /* bombs vs the cannon */
    if (!cannon.dying)
        for (i = 0; i < NBOMBS; i++)
            if (bombs[i].active && bombs[i].pos.x >= cannon.pos.x && bombs[i].pos.x <= cannon.pos.x + 15 &&
                bombs[i].pos.y + 6 >= cannon.pos.y + 12 && bombs[i].pos.y <= cannon.pos.y + 19) {
                bombs[i].active = 0;
                lose_life();
            }

    /* the march: faster as the formation thins out */
    if (--form_timer == 0) {
        form_timer = (unsigned char)(alive_count / 2 + 1);
        if (formation_step()) {               /* landed */
            if (state == PLAYING) { lives = 1; lose_life(); }
            else if (state == ATTRACT) start(ATTRACT);
        }
    }
    draw_booms();

    if (alive_count == 0) {
        wave++;
        new_wave();
        if (state == ATTRACT) message(ATTRACT_TEXT);
    }
}

