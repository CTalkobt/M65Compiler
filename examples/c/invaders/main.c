/* invaders — a Space Invaders game for the MEGA65, built with cc45
 *
 * Shows off:
 *   - cc45's object extensions: a Vec2 with overloaded + / += / ==, game
 *     objects derived from an Entity base with virtual update() / draw(),
 *     updated through Entity pointers
 *   - VIC-IV graphics: the character set copied into bank 4 with
 *     dma_copy_far and redefined (aliens, shields), 16-colour sprites (the
 *     cannon, the UFO) with their own palette entries, 16-bit sprite
 *     pointers, colour RAM written with dma_fill_far
 *   - input: joystick port 2 or the keyboard (Z/X or , . to move, SPACE to
 *     fire), scanned directly (key_pressed)
 *   - sound: SID effects (shot, explosion, UFO) and the marching beat
 *   - file I/O: the high score is kept on disk ("invaders.hi" on device 8,
 *     fopen/fread/fwrite), read at the start and written after a game that
 *     beat it
 *
 * Without a player it runs an attract mode in which the computer plays.
 * FIRE or SPACE starts a game; RUN/STOP returns to BASIC.
 * The art is in gfx.h, generated by gen.py from ASCII pictures.
 */
#include <stdio.h>
#include <dma.h>
#include <mega65.h>
#include "gfx.h"

/* the program ends near $B200 with the file I/O: a 2 KB stack share (the
 * game needs little: its functions keep their variables in static storage)
 * leaves the heap fopen needs below the stack */
#pragma cc45 stack_size(2048)

#define COLS 80
#define ROWS 25
#define SCREEN      ((volatile unsigned char *)0x0800)
#define SCREEN_LIN  0x0000800UL
#define COLOR_LIN   0xFF80000UL
#define CHARROM_LIN 0xFF7E000UL      /* the MEGA65 character set */
#define CHARSET_LIN 0x004F800UL      /* our copy: bank 4 */
#define REG(a)      (*(volatile unsigned char *)(a))

/* custom glyphs (gfx.h order) */
#define CH_BASE    0x60
#define CH_ALIEN(type, frame) (CH_BASE + ((type) * 2 + (frame)) * 3)
#define CH_BOOM    (CH_BASE + 18)
#define CH_SHIELD  (CH_BASE + 21)    /* + 0 full, + 1 damaged, + 2 nearly gone */
#define CH_GROUND  (CH_BASE + 24)
#define CH_SPACE   0x20

/* layout (character rows) */
#define HUD_ROW     0
#define UFO_ROW     2
#define TOP_ROW     3
#define FORM_ROWS   5
#define FORM_COLS   11
#define ALIEN_STEP  4                 /* characters from one alien column to the next */
#define SHIELD_ROW  18                /* rows 18-19 */
#define CANNON_ROW  21
#define GROUND_ROW  22
#define TEXT_ROW    24                /* below the ground: nothing else draws there */

/* sprite coordinates: a character column is 4 sprite pixels, a row 8 */
#define SX(col) (24 + (col) * 4)
#define SY(row) (50 + (row) * 8)

/* sprites */
#define SPR_CANNON 0
#define SPR_SHOT   1
#define SPR_BOMB   2                  /* 2, 3, 4 */
#define NBOMBS     3
#define SPR_UFO    5

/* colours */
#define C_WHITE 1
#define C_RED 2
#define C_CYAN 3
#define C_PURPLE 4
#define C_GREEN 5
#define C_YELLOW 7

/* ------------------------------------------------------------------------ */
/* Sprite data and pointers (16-bit pointer mode: any 64-byte boundary)      */

static _Alignas(64) unsigned char sprite_mem[192 * 3 + 64 * 3];
#define SPRD_CANNON      (sprite_mem)
#define SPRD_CANNON_BOOM (sprite_mem + 192)
#define SPRD_UFO         (sprite_mem + 384)
#define SPRD_SHOT        (sprite_mem + 576)
#define SPRD_BOMB_A      (sprite_mem + 640)
#define SPRD_BOMB_B      (sprite_mem + 704)
static _Alignas(16) unsigned int sprite_ptr[8];
static unsigned char saved_regs[8];

/* A 16-colour sprite takes its colours from palette entries n * 16 ..
 * n * 16 + 15 (sprite n): sprite 0's are the standard 16 colours; the UFO
 * (sprite 5) gets a copy of them in entries 80-95, with its own brighter
 * red (entry 82) */
#define PAL_R(i) REG(0xD100 + (i))
#define PAL_G(i) REG(0xD200 + (i))
#define PAL_B(i) REG(0xD300 + (i))
static unsigned char saved_pal[48];

static void ufo_palette(void) {
    unsigned char i, base = SPR_UFO * 16;
    for (i = 0; i < 16; i++) {
        saved_pal[i] = PAL_R(base + i); saved_pal[16 + i] = PAL_G(base + i); saved_pal[32 + i] = PAL_B(base + i);
        PAL_R(base + i) = PAL_R(i); PAL_G(base + i) = PAL_G(i); PAL_B(base + i) = PAL_B(i);
    }
    PAL_R(base + 2) = 0xFF;      /* nibble-swapped intensities: full red, a little green and blue */
    PAL_G(base + 2) = 0x33;
    PAL_B(base + 2) = 0x33;
}

static void restore_palette(void) {
    unsigned char i, base = SPR_UFO * 16;
    for (i = 0; i < 16; i++) {
        PAL_R(base + i) = saved_pal[i]; PAL_G(base + i) = saved_pal[16 + i]; PAL_B(base + i) = saved_pal[32 + i];
    }
}

static void sprite_image(unsigned char n, unsigned char *data) {
    sprite_ptr[n] = (unsigned int)data / 64;
}

/* position a sprite (X above 255 through $D010) and show or hide it */
static void sprite_place(unsigned char n, signed int x, signed int y, unsigned char on) {
    unsigned char bit = (unsigned char)(1 << n);
    if (!on) { REG(0xD015) = REG(0xD015) & (unsigned char)~bit; return; }
    REG(0xD000 + n * 2) = (unsigned char)x;
    REG(0xD001 + n * 2) = (unsigned char)y;
    if (x > 255) REG(0xD010) = REG(0xD010) | bit;
    else REG(0xD010) = REG(0xD010) & (unsigned char)~bit;
    REG(0xD015) = REG(0xD015) | bit;
}

/* ------------------------------------------------------------------------ */
/* Sound: SID 1 voice 0 shots, voice 1 explosions, voice 2 the march; SID 2 */
/* voice 0 the UFO                                                          */

static unsigned char snd_shot_t, snd_boom_t, snd_beat_t, snd_beat_n;
static const unsigned char beat_notes[4] = {0x0C, 0x0B, 0x0A, 0x09};

static void snd_init(void) {
    volatile struct sid_voice *v;
    unsigned char i;
    for (i = 0; i < 3; i++) {
        v = SID1_VOICE(i);
        v->ctrl = 0;
        v->freq_hi = 0;
    }
    SID2_VOICE(0)->ctrl = 0;
    SID1_VOICE(0)->pw_lo = 0x00;
    SID1_VOICE(0)->pw_hi = 0x08;
    sid1->volume = 15;
    sid2->volume = 15;
}

static void snd_shot(void) {
    volatile struct sid_voice *v = SID1_VOICE(0);
    v->attack_decay = 0x08;
    v->sustain_release = 0x00;
    v->freq_lo = 0;
    v->freq_hi = 0x38;
    v->ctrl = SID_PULSE | SID_GATE;
    snd_shot_t = 10;
}

static void snd_boom(void) {
    volatile struct sid_voice *v = SID1_VOICE(1);
    v->attack_decay = 0x0A;
    v->sustain_release = 0x00;
    v->freq_lo = 0;
    v->freq_hi = 0x0A;
    v->ctrl = SID_NOISE | SID_GATE;
    snd_boom_t = 3;
}

static void snd_beat(void) {
    volatile struct sid_voice *v = SID1_VOICE(2);
    v->attack_decay = 0x06;
    v->sustain_release = 0x00;
    v->freq_lo = 0;
    v->freq_hi = beat_notes[snd_beat_n];
    snd_beat_n = (snd_beat_n + 1) & 3;
    v->ctrl = SID_TRIANGLE | SID_GATE;
    snd_beat_t = 3;
}

static void snd_ufo(unsigned char on, unsigned char phase) {
    volatile struct sid_voice *v = SID2_VOICE(0);
    if (!on) { v->ctrl = SID_SAWTOOTH; return; }
    v->attack_decay = 0x00;
    v->sustain_release = 0xF0;
    v->freq_lo = 0;
    v->freq_hi = 0x20 + (phase & 15) * 2;
    v->ctrl = SID_SAWTOOTH | SID_GATE;
}

/* once a frame: sweeps and gate releases */
static void snd_update(void) {
    if (snd_shot_t) {
        SID1_VOICE(0)->freq_hi = SID1_VOICE(0)->freq_hi - 3;
        if (--snd_shot_t == 0) SID1_VOICE(0)->ctrl = SID_PULSE;
    }
    if (snd_boom_t && --snd_boom_t == 0) SID1_VOICE(1)->ctrl = SID_NOISE;
    if (snd_beat_t && --snd_beat_t == 0) SID1_VOICE(2)->ctrl = SID_TRIANGLE;
}

static void snd_off(void) {
    SID1_VOICE(0)->ctrl = 0;
    SID1_VOICE(1)->ctrl = 0;
    SID1_VOICE(2)->ctrl = 0;
    SID2_VOICE(0)->ctrl = 0;
}

/* ------------------------------------------------------------------------ */
/* Screen helpers                                                           */

static void color_row(unsigned char row, unsigned char color) {
    dma_fill_far(COLOR_LIN + (unsigned int)row * COLS, COLS, color);
}

static void put_text(unsigned char row, unsigned char col, const char *s) {
    volatile unsigned char *p = SCREEN + row * COLS + col;
    while (*s) *p++ = (unsigned char)*s++;
}

static void put_number(unsigned char row, unsigned char col, unsigned int v, unsigned char digits) {
    volatile unsigned char *p = SCREEN + row * COLS + col + digits;
    while (digits--) {
        *--p = (unsigned char)(0x30 + v % 10);
        v /= 10;
    }
}

static void clear_row(unsigned char row) {
    dma_fill_far(SCREEN_LIN + (unsigned int)row * COLS, COLS, CH_SPACE);
}

#define ATTRACT_TEXT s"invaders - fire/space: play - crsr z/x , . joystick: move - run/stop: quit"

/* centred text on TEXT_ROW (empty clears it; at most 80 characters) */
static void message(const char *s) {
    unsigned char n = 0;
    clear_row(TEXT_ROW);
    while (s[n] && n < COLS) n++;
    put_text(TEXT_ROW, (unsigned char)((COLS - n) / 2), s);
    color_row(TEXT_ROW, C_YELLOW);
}

/* ------------------------------------------------------------------------ */
/* Random numbers (16-bit xorshift)                                         */

static unsigned int rnd_state = 0xACE1;
static unsigned int rnd(void) {
    rnd_state ^= rnd_state << 7;
    rnd_state ^= rnd_state >> 9;
    rnd_state ^= rnd_state << 8;
    return rnd_state;
}

