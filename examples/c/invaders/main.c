/* The title screen                                                         */

/* the logo: 4 x 5 blocks a letter, a block two characters wide (square on
 * the 80-column screen), 2 characters between letters: 78 columns */
#define LOGO_ROW 1
#define LOGO_BLOCK 0xA0                   /* a reversed space: solid */
static const unsigned char logo_font[8][5] = {   /* a row: bit 3 the left block */
    {0xF, 0x6, 0x6, 0x6, 0xF},   /* I: ####  .##.  .##.  .##.  #### */
    {0x9, 0xD, 0xB, 0x9, 0x9},   /* N: #..#  ##.#  #.##  #..#  #..# */
    {0x9, 0x9, 0x9, 0x9, 0x6},   /* V: #..#  #..#  #..#  #..#  .##. */
    {0x6, 0x9, 0xF, 0x9, 0x9},   /* A: .##.  #..#  ####  #..#  #..# */
    {0xE, 0x9, 0x9, 0x9, 0xE},   /* D: ###.  #..#  #..#  #..#  ###. */
    {0xF, 0x8, 0xE, 0x8, 0xF},   /* E: ####  #...  ###.  #...  #### */
    {0xE, 0x9, 0xE, 0xA, 0x9},   /* R: ###.  #..#  ###.  #.#.  #..# */
    {0x7, 0x8, 0x6, 0x1, 0xE},   /* S: .###  #...  .##.  ...#  ###. */
};
static const unsigned char logo_colors[6] = {C_PURPLE, C_CYAN, C_GREEN, C_YELLOW, C_RED, C_WHITE};

static void draw_logo(void) {
    unsigned char letter, r, b;
    for (r = 0; r < 5; r++) {
        for (b = 0; b < COLS; b++) line[b] = CH_SPACE;
        for (letter = 0; letter < 8; letter++)
            for (b = 0; b < 4; b++)
                if (logo_font[letter][r] & (8 >> b))
                    line[1 + letter * 10 + b * 2] = line[2 + letter * 10 + b * 2] = LOGO_BLOCK;
        dma_copy_far(SCREEN_LIN + (unsigned int)(LOGO_ROW + r) * COLS, (unsigned long)(unsigned int)line, COLS);
    }
}

/* the score table: typed out a character every 2 frames, line by line
 * (done in about 4 seconds, before the attract mode takes over) */
#define TABLE_COL 30
static const char *const table_text[5] = {
    s"*score advance table*", s"= ? mystery", s"= 30 points", s"= 20 points", s"= 10 points"
};
static const unsigned char table_row[5] = {9, 12, 14, 16, 18};

static void title_frame(unsigned int t) {
    unsigned char i, n;
    unsigned int at = 25;                 /* the table starts typing after 25 frames */

    /* the logo's rows in cycling colours */
    for (i = 0; i < 5; i++)
        color_row(LOGO_ROW + i, logo_colors[(unsigned char)(i + (t >> 3)) % 6]);

    /* the table, typed out */
    for (i = 0; i < 5; i++) {
        const char *s = table_text[i];
        unsigned char len = 0;
        while (s[len]) len++;
        n = t < at ? 0 : (t - at) / 2 > len ? len : (unsigned char)((t - at) / 2);
        if (n) {
            volatile unsigned char *p = SCREEN + table_row[i] * COLS + TABLE_COL + (i ? 5 : -5);
            unsigned char k;
            for (k = 0; k < n; k++) p[k] = (unsigned char)s[k];
        }
        at += len * 2 + 6;
    }

    /* the aliens beside their points, marching in place */
    for (i = 0; i < 3; i++) {
        volatile unsigned char *p = SCREEN + table_row[2 + i] * COLS + TABLE_COL;
        unsigned char base = CH_ALIEN(i == 0 ? 0 : i == 1 ? 1 : 2, (t >> 5) & 1);
        p[0] = base; p[1] = (unsigned char)(base + 1); p[2] = (unsigned char)(base + 2);
    }

    /* "push fire": blinking */
    if ((t & 31) == 0) put_text(22, 26, s"push fire or space to play");
    else if ((t & 31) == 20) clear_row(22);
}

/* the title's fixed lines: row, column, colour (of the whole row), text */
