/* ------------------------------------------------------------------------ */

static void wait_vsync(void) {
    while (REG(0xD012) == 0) ;
    while (REG(0xD012) != 0 || (REG(0xD011) & 0x80)) ;
}

static void setup(void) {
    unsigned char r;
    /* save what we change */
    saved_regs[0] = REG(0xD068); saved_regs[1] = REG(0xD069); saved_regs[2] = REG(0xD06A);
    saved_regs[3] = REG(0xD06C); saved_regs[4] = REG(0xD06D); saved_regs[5] = REG(0xD06E);
    saved_regs[6] = REG(0xD020); saved_regs[7] = REG(0xD021);

    /* the character set: the ROM's copied to bank 4, our glyphs over CH_BASE.. */
    dma_copy_far(CHARSET_LIN, CHARROM_LIN, 2048);
    dma_copy_far(CHARSET_LIN + CH_BASE * 8, (unsigned long)(unsigned int)glyph_data, sizeof glyph_data);
    REG(0xD068) = (unsigned char)CHARSET_LIN;
    REG(0xD069) = (unsigned char)(CHARSET_LIN >> 8);
    REG(0xD06A) = (unsigned char)(CHARSET_LIN >> 16);

    /* sprites: data, 16-bit pointers, 16-colour cannon and UFO */
    for (r = 0; r < 6; r++)
        dma_copy_far(SPRITE_LIN + sprite_images[r].at, (unsigned long)(unsigned int)sprite_images[r].data,
                     sprite_images[r].size);
    sprite_image(SPR_CANNON, SPRD_CANNON);
    sprite_image(SPR_SHOT, SPRD_SHOT);
    for (r = 0; r < NBOMBS; r++) sprite_image(SPR_BOMB + r, SPRD_BOMB_A);
    sprite_image(SPR_UFO, SPRD_UFO);
    REG(0xD06C) = (unsigned char)(unsigned int)sprite_ptr;
    REG(0xD06D) = (unsigned char)((unsigned int)sprite_ptr >> 8);
    REG(0xD06E) = 0x80;                                   /* bank 0, 16-bit pointers */
    REG(0xD06B) = (1 << SPR_CANNON) | (1 << SPR_UFO);     /* 16-colour sprites */
    REG(0xD057) = (1 << SPR_CANNON) | (1 << SPR_UFO);     /* 8 bytes a row */
    REG(0xD027 + SPR_CANNON) = 0;                         /* transparent colour 0 */
    REG(0xD027 + SPR_UFO) = 0;
    ufo_palette();
    REG(0xD027 + SPR_SHOT) = C_WHITE;
    for (r = 0; r < NBOMBS; r++) REG(0xD027 + SPR_BOMB + r) = C_YELLOW;
    REG(0xD01B) = 0;                                      /* sprites in front */
    REG(0xD015) = 0;

    /* objects */
    cannon.sprite = SPR_CANNON;
    shot.sprite = SPR_SHOT;
    shot.vel.x = 0; shot.vel.y = -5;
    for (r = 0; r < NBOMBS; r++) { bombs[r].sprite = SPR_BOMB + r; bombs[r].vel.x = 0; bombs[r].vel.y = 2; }
    ufo.sprite = SPR_UFO;
    ufo.vel.y = 0;
    entities[0] = (struct Entity *)&cannon;
    entities[1] = (struct Entity *)&shot;
    entities[2] = (struct Entity *)&ufo;
    for (r = 0; r < NBOMBS; r++) entities[3 + r] = (struct Entity *)&bombs[r];

    /* the screen */
    fps = (REG(0xD06F) & 0x80) ? 60 : 50;  /* NTSC or PAL */
    REG(0xD020) = 0;
    REG(0xD021) = 0;
    putchar(0x93);
    for (r = 0; r < ROWS; r++) color_row(r, C_WHITE);
    dma_fill_far(SCREEN_LIN + GROUND_ROW * COLS, COLS, CH_GROUND);
    color_row(GROUND_ROW, C_GREEN);
    snd_init();
}

static void restore(void) {
    REG(0xD015) = 0;
    REG(0xD06B) = 0;
    REG(0xD057) = 0;
    REG(0xD068) = saved_regs[0]; REG(0xD069) = saved_regs[1]; REG(0xD06A) = saved_regs[2];
    REG(0xD06C) = saved_regs[3]; REG(0xD06D) = saved_regs[4]; REG(0xD06E) = saved_regs[5];
    REG(0xD020) = saved_regs[6]; REG(0xD021) = saved_regs[7];
    snd_off();
    restore_palette();
    putchar(0x05);   /* white text */
    putchar(0x93);
}

/* -DINV_TEST: the high-score test (headless xemu with a D81 on device 8):
 * $C0C0/1 the score read at the start, then a game that beats it by 1230
 * ends, the score is saved and read back into $C0C2/3; $C0C4 = $AA */
int main(void) {
    load_hiscore();
    setup();
    ai_col = -1;
    show_title();
#ifdef INV_TEST
    REG(0xC0C0) = (unsigned char)hiscore;
    REG(0xC0C1) = (unsigned char)(hiscore >> 8);
    start(PLAYING);
    add_score(hiscore + 1230);
    state = GAME_OVER;
    state_timer = 1;
#endif
    input_flush();                        /* no stale key presses */
    while (!quit_key && !stop_pressed()) {
        wait_vsync();
        frame++;
        snd_update();
        if (state == TITLE) {
            /* FIRE plays; any other input keeps the title up; 5 seconds
               without input: the attract mode, for 20 seconds */
            unsigned char j = read_input();
            if (j & JOY_FIRE) { start(PLAYING); message(s""); }
            else {
                if (j) state_frames = 0;
                else if (++state_frames >= 5u * fps) {
                    start(ATTRACT);
                    state_frames = 20u * fps;
                }
                if (state == TITLE) { title_frame(title_t); title_t++; continue; }
            }
        } else if (state == ATTRACT) {
            unsigned char j = read_input();
            if (j & JOY_FIRE) { start(PLAYING); message(s""); }
            else if (j || --state_frames == 0) { show_title(); continue; }
        } else if (state == GAME_OVER && --state_timer == 0) {
            save_hiscore();
            show_title();
#ifdef INV_TEST
            quit_key = 1;
#endif
            continue;
        }
        play_frame();
    }
    snd_off();
    save_hiscore();                       /* quit during a game that beat it */
    restore();
#ifdef INV_TEST
    hiscore = saved_hi = 0;
    load_hiscore();
    REG(0xC0C2) = (unsigned char)hiscore;
    REG(0xC0C3) = (unsigned char)(hiscore >> 8);
    REG(0xC0C4) = 0xAA;
#endif
    return 0;
}
