# mono sprites: 24 x 21, 3 bytes a row
def mono(rows):
    data = []
    for y in range(21):
        r = rows[y] if y < len(rows) else ''
        r = r.ljust(24, '.')
        for x in range(0, 24, 8): data.append(int(r[x:x+8].replace('#','1').replace('.','0'), 2))
    return data + [0]
