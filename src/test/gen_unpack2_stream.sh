#!/bin/bash
# gen_unpack2_stream.sh OUT_DIR: the images of test_unpack2_xemu.c (raw 4-bit
# pixels), packed by pack45 --image (format 2, #666) as OUT_DIR/unpack2_stream.h
# with the bytes each unpacks to:
#   a  64x40, 16 colours, smooth along the rows (coded from the left)
#   b  256x3, 2 colours, the same in every row (coded from above)
#   c  10x5, 1 colour (a row of 5 bytes: an odd number)
set -e
d=${1:?}
python3 - "$d" <<'PY'
import sys
d = sys.argv[1]
def raw(name, w, h, px):
    out = bytearray()
    for y in range(h):
        for x in range(0, w, 2):
            out.append(px(x, y) | px(x + 1, y) << 4)
    open(f"{d}/unpack2_{name}.raw", "wb").write(out)
# a: bands of 4 pixels stepping through 16 colours, shifted a little each row
raw("a", 64, 40, lambda x, y: ((x + (y * 3) // 4) // 4) % 16)
# b: a pattern along x repeated down the rows, colours 3 and 12
raw("b", 256, 3, lambda x, y: 12 if (x * 37 + (x >> 3)) % 7 < 3 else 3)
raw("c", 10, 5, lambda x, y: 9)
PY
pk() {   # name width dest extra -> the line pack45 prints
    ./bin/pack45 --image --raw --width "$2" -d "$3" "$d/unpack2_$1.raw" "$d/unpack2_$1_$4.pak"
}
la=$(pk a 64 0x40000 chip)
lb=$(pk b 256 0x40000 chip)
lc=$(pk c 10 0x40000 chip)
pk a 64 0x8000000 attic >/dev/null
case "$la" in *"from the left"*) ;; *) echo "gen_unpack2_stream.sh: image a not coded from the left: $la" >&2; exit 1 ;; esac
case "$lb" in *"from above"*) ;; *) echo "gen_unpack2_stream.sh: image b not coded from above: $lb" >&2; exit 1 ;; esac
inplace=$(echo "$la" | sed -n 's/.*(offset \([0-9]*\)).*/\1/p')
arr() { echo "static const unsigned char $1[] = {"; od -An -v -tu1 "$2" | sed 's/  */, /g; s/^, //; s/$/,/'; echo "};"; }
{
    echo "/* generated by src/test/gen_unpack2_stream.sh */"
    echo "#define A_INPLACE ${inplace}UL"
    arr a_chip "$d/unpack2_a_chip.pak"
    arr a_attic "$d/unpack2_a_attic.pak"
    arr b_chip "$d/unpack2_b_chip.pak"
    arr c_chip "$d/unpack2_c_chip.pak"
    arr a_img "$d/unpack2_a.raw"
    arr b_img "$d/unpack2_b.raw"
    arr c_img "$d/unpack2_c.raw"
} > "$d/unpack2_stream.h"
