#!/bin/bash
# gen_unpack_stream.sh OUT_DIR: the pattern of test_unpack_xemu.c, packed by
# pack45 to $40000 and to $8000000, as build/test/unpack_stream.h
set -e
d=${1:?}
python3 - "$d/unpack_data.bin" <<'PY'
import sys
out = bytearray()
for i in range(5000):
    b = (i >> 8) % 3
    out.append((i * 7) & 0xFF if b == 0 else (0x41 + i % 13) if b == 1 else 0x55)
open(sys.argv[1], 'wb').write(out)
PY
inplace=$(./bin/pack45 --raw -d 0x40000 "$d/unpack_data.bin" "$d/unpack_chip.pak" | sed -n 's/.*(offset \([0-9]*\)).*/\1/p')
./bin/pack45 --raw -d 0x8000000 "$d/unpack_data.bin" "$d/unpack_attic.pak" >/dev/null
{
    echo "/* generated by src/test/gen_unpack_stream.sh */"
    echo "#define STREAM_CHIP_INPLACE ${inplace}UL"
    echo "static const unsigned char stream_chip[] = {"
    od -An -v -tu1 "$d/unpack_chip.pak" | sed 's/  */, /g; s/^, //; s/$/,/'
    echo "};"
    echo "static const unsigned char stream_attic[] = {"
    od -An -v -tu1 "$d/unpack_attic.pak" | sed 's/  */, /g; s/^, //; s/$/,/'
    echo "};"
} > "$d/unpack_stream.h"
