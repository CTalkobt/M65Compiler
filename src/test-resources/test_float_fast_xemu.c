volatile float one = 1.0, tenth = 0.1, big = 65539.0;

static int same(float f, const unsigned char *e) {
    unsigned char *p = (unsigned char *)&f;
    /* (a zero: the exponent 0) */
    if (e[0] == 0) return p[0] == 0;
    return memcmp(p, e, 5) == 0;
}

int main(void) {
    unsigned char k, ok[5];
    float a, b, r;
    memset(ok, 1, sizeof ok);
    for (k = 0; k < N; k++) {
        memcpy(&a, rows[k].a, 5);
        memcpy(&b, rows[k].b, 5);
        r = a + b; if (!same(r, rows[k].sum)) ok[0] = 0;
        r = a - b; if (!same(r, rows[k].diff)) ok[1] = 0;
        r = a * b; if (!same(r, rows[k].prod)) ok[2] = 0;
        r = a / b; if (!same(r, rows[k].quot)) ok[3] = 0;
        if ((a < b ? 0xFF : a > b ? 1 : 0) != rows[k].cmp || (a == b) != (rows[k].cmp == 0)) ok[4] = 0;
    }
    for (k = 0; k < 5; k++) OUT[k] = ok[k];
    OUT[5] = 1;
    for (k = 0; k < N; k++) {
        memcpy(&a, rows[k].a, 5);
        if (a * one != a || a / one != a) OUT[5] = 0;
    }
    if (one * tenth != tenth || big / one - big != 0.0) OUT[5] = 0;
    OUT[6] = 0xAA;
    return 0;
}
